module.exports = function (eleventyConfig) {
  eleventyConfig.addPassthroughCopy({ "src/assets": "assets" });
  // Vendored Calcite icons, copied rather than re-hosted from a second place:
  // animate.py base64s the same files into the animation pages, and their
  // licence allows redistribution only without modification. One source.
  eleventyConfig.addPassthroughCopy({ "../src/schematic/page/icons/*.svg": "assets/icons" });
  // Browsers request /favicon.ico regardless of what the head says.
  eleventyConfig.addPassthroughCopy({ "src/assets/favicon/favicon.ico": "favicon.ico" });
  // Maps are generated by the Python pipeline into src/maps. They must be
  // copied byte-for-byte: the animation pages are complete documents, and
  // letting Eleventy treat them as Nunjucks templates both rewrites their URLs
  // and risks mangling the embedded script.
  eleventyConfig.addPassthroughCopy({ "src/maps": "maps" });
  eleventyConfig.ignores.add("src/maps/**");

  eleventyConfig.addFilter("formatDate", function (value) {
    if (!value) return "";
    var parsed = typeof value === "string" && /^\d{4}-\d{2}-\d{2}$/.test(value)
      ? new Date(value + "T00:00:00Z")
      : new Date(value);
    if (isNaN(parsed.getTime())) return String(value);
    return new Intl.DateTimeFormat("en-US", {
      year: "numeric", month: "long", day: "numeric", timeZone: "UTC"
    }).format(parsed);
  });

  eleventyConfig.addFilter("thousands", function (value) {
    return Number(value || 0).toLocaleString("en-US");
  });

  // Pull one network out of the generated list by key. The essay names the
  // cities it shows; this keeps networks.json a plain list rather than making
  // site.py write a second, keyed copy of the same entries.
  eleventyConfig.addFilter("network", function (list, key) {
    return (list || []).find(function (n) { return n.key === key; });
  });

  // Inline a generated SVG so it inherits the page's theme variables. Reading
  // it as an <img> would sandbox it away from the CSS custom properties that
  // colour the stations and labels.
  var fs = require("fs");
  var path = require("path");
  eleventyConfig.addFilter("inlineMap", function (file) {
    var full = path.join(__dirname, "src", "maps", file);
    if (!fs.existsSync(full)) return "<!-- missing map: " + file + " -->";
    return fs.readFileSync(full, "utf8")
      // The generated file sets a pixel width/height; inside the page it should
      // scale to its container instead.
      .replace(/^<svg([^>]*?)\swidth="[^"]*"\sheight="[^"]*"/, "<svg$1");
  });

  // An unfurler -- Slack, Teams, Messenger -- fetches og:image from its own
  // servers, with no page to resolve a relative path against, so those two tags
  // are the one place on this site that needs a whole https:// URL. This is
  // `url` with the origin on the front rather than a second prefix
  // implementation: the day pathPrefix changes, only one of them has to know.
  eleventyConfig.addFilter("absolute", function (p) {
    var origin = (require("./src/_data/site.json").origin || "").replace(/\/$/, "");
    return origin + eleventyConfig.getFilter("url")(p);
  });

  return {
    // GitHub Pages serves a project repo from a subpath, so every absolute URL
    // needs prefixing. The `url` filter used throughout the templates does that
    // from here; anything built outside Eleventy has to apply it itself, which
    // is why site.py reads the same value.
    pathPrefix: require("./src/_data/site.json").pathPrefix || "/",
    dir: { input: "src", includes: "_includes", data: "_data", output: "dist" },
    markdownTemplateEngine: "njk",
    htmlTemplateEngine: "njk",
    templateFormats: ["md", "njk", "html"]
  };
};
